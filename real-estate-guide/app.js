  const rerender = (page = 1) => {
    renderStats();
    renderTools();
    renderTabs();
    renderPanel(activeCategoryId, page);
  };

  if (progress) {
    progress.hidden = true;
    progress.innerHTML = "";
  }

  tools?.addEventListener("input", (event) => {
    if (event.target.id !== "materialSearchInput") return;
    query = event.target.value.trim();
    Object.keys(digestPages).forEach((key) => { digestPages[key] = 1; });
    rerender(1);
    document.querySelector("#materialSearchInput")?.focus();
  });

  tools?.addEventListener("click", (event) => {
    const filter = event.target.closest("[data-material-filter]");
    if (!filter) return;
    mode = filter.dataset.materialFilter;
    Object.keys(digestPages).forEach((key) => { digestPages[key] = 1; });
    rerender(1);
  });

